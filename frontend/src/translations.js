const heToEn = {};
const enToHe = {};
for (const [he, en] of PAIRS) {
  if (!(he in heToEn)) heToEn[he] = en;
  if (!(en in enToHe)) enToHe[en] = he;
}

export function translate(text, language) {
  if (text == null) return text;
  if (language === "en") return heToEn[text] ?? text;
  return enToHe[text] ?? text;
}
